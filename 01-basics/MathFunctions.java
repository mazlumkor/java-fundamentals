public class MathFunctions {
    public static void main(String[] args) {
        System.out.println(Math.abs(-128));/*when you write your varible in math.abs,
        the variable will be enclosed within an absolute value*/
        System.out.println(Math.sqrt(25));//Karekök alır.
        System.out.println(Math.pow(2,3));//ilk girilen değerin ikinci girilen değer kadar üssünü alır.
        System.out.println(Math.max(80,45));// girilen değerler arasında daha büyük olanı verir.
        System.out.println(Math.min(80,45));// girilen değerler arasında daha küçük olanı verir.
        System.out.println(Math.ceil(2.2));// girilen ondalıklı sayıyı bir üstteki tam sayıya yuvarlar.
        System.out.println(Math.floor(2.8));//  girilen ondalıklı sayıyı bir alttaki tam sayıya yuvarlar.
        System.out.println(Math.round(2.7));// girilen sayıyı yakın olan ondalık tam sayıya yuvarlar.
        System.out.println(Math.random());

    }
}
